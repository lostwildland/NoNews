import Foundation
import os
import RSCore
import RSParser

@MainActor final class OPMLFile {
	private let fileURL: URL
	private weak var account: Account?

	private var isDirty = false {
		didSet {
			if isDirty { queueSaveToDiskIfNeeded() }
		}
	}
	private let saveQueue = CoalescingQueue(name: "Save Queue", interval: 0.5)
	private static let logger = Logger(subsystem: Logger.nnwSubsystem, category: "OPMLFile")

	init(filename: String, account: Account) {
		self.fileURL = URL(fileURLWithPath: filename)
		self.account = account
	}

	func markAsDirty() {
		isDirty = true
	}

	func load() {
		guard let account, let fileData = opmlFileData(), let opmlItems = parsedOPMLItems(fileData: fileData) else {
			return
		}

		BatchUpdate.shared.perform {
			account.loadOPMLItems(opmlItems, isManualImport: false)
		}
	}

	@discardableResult func save() -> Bool {
		guard let account, !account.isDeleted else { return false }
		let opmlDocumentString = opmlDocument(account: account)

		do {
			try opmlDocumentString.write(to: fileURL, atomically: true, encoding: .utf8)
			return true
		} catch let error as NSError {
			Self.logger.error("OPML save to disk failed: \(error.localizedDescription)")
			return false
		}
	}

	@objc func saveToDiskIfNeeded() {
		_ = flush()
	}

	func flush() -> Bool {
		guard isDirty else { return true }
		guard save() else { return false }
		isDirty = false
		return true
	}
}

private extension OPMLFile {

	func queueSaveToDiskIfNeeded() {
		if Thread.isMainThread {
			MainActor.assumeIsolated {
				saveQueue.add(self, #selector(saveToDiskIfNeeded))
			}
		} else {
			Task { @MainActor in
				saveQueue.add(self, #selector(saveToDiskIfNeeded))
			}
		}
	}

	func opmlFileData() -> Data? {
		var fileData: Data?

		do {
			fileData = try Data(contentsOf: fileURL)
		} catch {
			Self.logger.error("OPML read from disk failed: \(error.localizedDescription)")
		}

		return fileData
	}

	func parsedOPMLItems(fileData: Data) -> [OPMLItem]? {
		let parserData = ParserData(url: fileURL.absoluteString, data: fileData)
		var opmlDocument: OPMLDocument?

		do {
			opmlDocument = try OPMLParser.parseOPML(with: parserData)
		} catch {
			Self.logger.error("OPML import failed: \(error.localizedDescription)")
			return nil
		}

		return opmlDocument?.children
	}

	func opmlDocument(account: Account) -> String {
		let escapedTitle = account.nameForDisplay.escapingSpecialXMLCharacters
		let openingText =
		"""
		<?xml version="1.0" encoding="UTF-8"?>
		<!-- OPML generated by NetNewsWire -->
		<opml version="1.1">
		<head>
		<title>\(escapedTitle)</title>
		</head>
		<body>

		"""

		let middleText = account.OPMLString(indentLevel: 0, allowCustomAttributes: true)

		let closingText =
		"""
				</body>
			</opml>
			"""

		let opml = openingText + middleText + closingText
		return opml
	}
}
